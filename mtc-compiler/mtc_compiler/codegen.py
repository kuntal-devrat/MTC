Q15_SCALE = 32768
TARGET_RAM_BUDGETS = {
    "esp32": 64 * 1024,
    "stm32f401": 64 * 1024,
    "host": 64 * 1024,
    "wokwi": 64 * 1024,
}


@dataclass(frozen=True)
class Compilation:
    files: dict[str, str]
    stages: tuple[DenseStage, ...]
    analysis: AnalysisResult
    memory: MemoryPlan
    target: str


def _to_q15(value: float) -> int:
    return max(-Q15_SCALE, min(Q15_SCALE - 1, round(value * Q15_SCALE)))


def _weight_values(stages: tuple[DenseStage, ...], seed: int) -> tuple[list[int], list[int]]:
    generator = random.Random(seed)
    weights: list[int] = []
    biases: list[int] = []
    for stage in stages:
        bound = math.sqrt(6.0 / (stage.in_features + stage.out_features))
        weights.extend(
            _to_q15(generator.uniform(-bound, bound))
            for _ in range(stage.in_features * stage.out_features)
        )
        biases.extend([0] * stage.out_features)
    return weights, biases


def _weight_offsets(stages: tuple[DenseStage, ...]) -> tuple[list[int], list[int], int]:
    weight_offsets: list[int] = []
    bias_offsets: list[int] = []
    weight_cursor = 0
    bias_cursor = 0
    for stage in stages:
        weight_offsets.append(weight_cursor)
        bias_offsets.append(bias_cursor)
        weight_cursor += stage.in_features * stage.out_features
        bias_cursor += stage.out_features
    return weight_offsets, bias_offsets, weight_cursor


def _c_array(values: list[int], values_per_line: int = 12) -> str:
    lines = []
    for start in range(0, len(values), values_per_line):
        lines.append("    " + ", ".join(str(value) for value in values[start:start + values_per_line]))
    return ",\n".join(lines)


def _sigmoid_table() -> str:
    values = [
        _to_q15(1.0 / (1.0 + math.exp(-(-1.0 + 2.0 * index / 256.0))))
        for index in range(257)
    ]
    return _c_array(values)


def _render_header(config: ModelConfig, stages: tuple[DenseStage, ...], memory: MemoryPlan) -> str:
    return f'''/* Generated by MTC {__version__}. Do not edit. */
#ifndef MTC_MODEL_H
#define MTC_MODEL_H

#include <stdint.h>

#define MTC_INPUT_SIZE {stages[0].in_features}U
#define MTC_OUTPUT_SIZE {stages[-1].out_features}U
#define MTC_LAYER_COUNT {len(stages)}U
#define MTC_TRAIN_SAMPLES {len(config.training_data)}U
#define MTC_EPOCHS {config.epochs}U
#define MTC_POOL_ELEMENTS {max(1, memory.pool_elements)}U
#define MTC_STATIC_RAM_BYTES {memory.total_static_ram_bytes}U
#define MTC_Q15_SCALE {Q15_SCALE}L

#ifdef __cplusplus
extern "C" {{
#endif

void mtc_reset(void);
void mtc_forward(const int16_t *input, int16_t *output);
int16_t mtc_loss_q15(const int16_t *prediction, const int16_t *target);
int16_t mtc_train_sample(const int16_t *input, const int16_t *target);

#ifdef __cplusplus
}}
#endif

#endif
'''


def _render_model_source(
    config: ModelConfig,
    stages: tuple[DenseStage, ...],
    memory: MemoryPlan,
    weights: list[int],
    weight_offsets: list[int],
    bias_offsets: list[int],
) -> str:
    weight_count = len(weights)
    bias_count = sum(stage.out_features for stage in stages)
    weights_text = _c_array(weights)
    biases_text = _c_array([0] * bias_count)
    needs_sigmoid = any(stage.activation == "sigmoid" for stage in stages)

    helpers = '''
static int16_t mtc_saturate_q15(int64_t value) {
    if (value > 32767) return 32767;
    if (value < -32768) return -32768;
    return (int16_t)value;
}

static int64_t mtc_round_q30(int64_t value) {
    if (value >= 0) return (value + 16384) / 32768;
    return -((-value + 16384) / 32768);
}

static int16_t mtc_multiply_q15(int16_t left, int16_t right) {
    return mtc_saturate_q15(mtc_round_q30((int64_t)left * (int64_t)right));
}
'''
    if needs_sigmoid:
        helpers += f'''
static const int16_t mtc_sigmoid_table[257] = {{
{_sigmoid_table()}
}};

static int16_t mtc_sigmoid_q15(int16_t value) {{
    uint32_t shifted = (uint32_t)((int32_t)value + 32768);
    uint32_t scaled = shifted * 256U;
    uint32_t index = scaled / 65535U;
    uint32_t remainder = scaled - index * 65535U;
    int32_t lower;
    int32_t difference;
    if (index >= 256U) return mtc_sigmoid_table[256];
    lower = mtc_sigmoid_table[index];
    difference = (int32_t)mtc_sigmoid_table[index + 1U] - lower;
    return mtc_saturate_q15((int64_t)lower + ((int64_t)difference * remainder) / 65535);
}}
'''

    output_allocations = [
        f"    int16_t *activation_{stage.index} = "
        f"&mtc_memory_pool[{memory.offset(f'activation_{stage.index}')}];"
        for stage in stages
    ]
    forward_blocks = []
    input_name = "input"
    for stage, weight_offset, bias_offset in zip(stages, weight_offsets, bias_offsets):
        activation_name = f"activation_{stage.index}"
        block = f'''
    for (uint32_t output_index = 0; output_index < {stage.out_features}U; ++output_index) {{
        int64_t accumulator = (int64_t)mtc_biases[{bias_offset}U + output_index] * 32768;
        for (uint32_t input_index = 0; input_index < {stage.in_features}U; ++input_index) {{
            accumulator += (int64_t)mtc_weights[{weight_offset}U + output_index * {stage.in_features}U + input_index]
                         * (int64_t){input_name}[input_index];
        }}
        {activation_name}[output_index] = mtc_saturate_q15(mtc_round_q30(accumulator));
    }}
'''
        if stage.activation == "relu":
            block += f'''    for (uint32_t index = 0; index < {stage.out_features}U; ++index) {{
        if ({activation_name}[index] < 0) {activation_name}[index] = 0;
    }}
'''
        elif stage.activation == "sigmoid":
            block += f'''    for (uint32_t index = 0; index < {stage.out_features}U; ++index) {{
        {activation_name}[index] = mtc_sigmoid_q15({activation_name}[index]);
    }}
'''
        forward_blocks.append(block)
        input_name = activation_name

    delta_a_offset = memory.offset("delta_a")
    delta_b_offset = memory.offset("delta_b")
    delta_length = max(stage.out_features for stage in stages)
    backward_blocks = []
    for stage_index in range(len(stages) - 1, -1, -1):
        stage = stages[stage_index]
        weight_offset = weight_offsets[stage_index]
        bias_offset = bias_offsets[stage_index]
        activation_offset = memory.offset(f"activation_{stage_index}")
        activation_derivative = ""
        if stage.activation == "relu":
            activation_derivative = f'''
        if (mtc_memory_pool[{activation_offset}U + output_index] <= 0) {{
            mtc_delta_current[output_index] = 0;
        }}
'''
        elif stage.activation == "sigmoid":
            activation_derivative = f'''
        int16_t activation_value = mtc_memory_pool[{activation_offset}U + output_index];
        int16_t one_minus_activation = (int16_t)(32767 - activation_value);
        mtc_delta_current[output_index] = mtc_multiply_q15(
            mtc_delta_current[output_index],
            mtc_multiply_q15(activation_value, one_minus_activation));
'''

        previous_gradient = ""
        input_pointer = "input" if stage_index == 0 else f"mtc_memory_pool + {memory.offset(f'activation_{stage_index - 1}')}U"
        if stage_index > 0:
            previous_gradient = f'''
    for (uint32_t input_index = 0; input_index < {stage.in_features}U; ++input_index) {{
        int64_t accumulator = 0;
        for (uint32_t output_index = 0; output_index < {stage.out_features}U; ++output_index) {{
            accumulator += (int64_t)mtc_weights[{weight_offset}U + output_index * {stage.in_features}U + input_index]
                         * (int64_t)mtc_delta_current[output_index];
        }}
        mtc_delta_previous[input_index] = mtc_saturate_q15(mtc_round_q30(accumulator));
    }}
'''

        update_block = f'''
    for (uint32_t output_index = 0; output_index < {stage.out_features}U; ++output_index) {{
        for (uint32_t input_index = 0; input_index < {stage.in_features}U; ++input_index) {{
            uint32_t weight_index = {weight_offset}U + output_index * {stage.in_features}U + input_index;
            int16_t gradient = mtc_multiply_q15(mtc_delta_current[output_index],
                                                  ({input_pointer})[input_index]);
            int16_t update = mtc_multiply_q15(mtc_learning_rate, gradient);
            mtc_weights[weight_index] = mtc_saturate_q15((int32_t)mtc_weights[weight_index] - update);
        }}
        int16_t bias_update = mtc_multiply_q15(mtc_learning_rate, mtc_delta_current[output_index]);
        mtc_biases[{bias_offset}U + output_index] =
            mtc_saturate_q15((int32_t)mtc_biases[{bias_offset}U + output_index] - bias_update);
    }}
'''
        backward_blocks.append(f'''
    for (uint32_t output_index = 0; output_index < {stage.out_features}U; ++output_index) {{{activation_derivative}
    }}
{previous_gradient}{update_block}
    if ({stage_index}U > 0U) {{
        int16_t *swap = mtc_delta_current;
        mtc_delta_current = mtc_delta_previous;
        mtc_delta_previous = swap;
    }}
''')

    output_pointer = f"mtc_memory_pool + {memory.offset(f'activation_{len(stages) - 1}')}U"
    return f'''/* Generated by MTC {__version__}. Do not edit. */
#include "mtc_model.h"

#include <stddef.h>

static int16_t mtc_memory_pool[MTC_POOL_ELEMENTS];
static const int16_t mtc_initial_weights[{max(1, weight_count)}U] = {{
{weights_text}
}};
static const int16_t mtc_initial_biases[{max(1, bias_count)}U] = {{
{biases_text}
}};
#define mtc_weights (mtc_memory_pool + {memory.offset('weights')}U)
#define mtc_biases (mtc_memory_pool + {memory.offset('biases')}U)
static const int16_t mtc_learning_rate = {_to_q15(config.optimizer.learning_rate)};
{helpers}

void mtc_reset(void) {{
    for (size_t index = 0; index < {weight_count}U; ++index) {{
        mtc_weights[index] = mtc_initial_weights[index];
    }}
    for (size_t index = 0; index < {bias_count}U; ++index) {{
        mtc_biases[index] = mtc_initial_biases[index];
    }}
}}

void mtc_forward(const int16_t *input, int16_t *output) {{
{chr(10).join(output_allocations)}
{chr(10).join(forward_blocks)}
    for (uint32_t index = 0; index < MTC_OUTPUT_SIZE; ++index) {{
        output[index] = ({output_pointer})[index];
    }}
}}

int16_t mtc_loss_q15(const int16_t *prediction, const int16_t *target) {{
    int64_t total = 0;
    for (uint32_t index = 0; index < MTC_OUTPUT_SIZE; ++index) {{
        int64_t difference = (int32_t)prediction[index] - target[index];
        total += difference * difference;
    }}
    return mtc_saturate_q15(mtc_round_q30(total / MTC_OUTPUT_SIZE));
}}

int16_t mtc_train_sample(const int16_t *input, const int16_t *target) {{
    int16_t *prediction = {output_pointer};
    int16_t *mtc_delta_current = &mtc_memory_pool[{delta_a_offset}U];
    int16_t *mtc_delta_previous = &mtc_memory_pool[{delta_b_offset}U];
    int16_t loss;
    (void){delta_length}U;
    mtc_forward(input, prediction);
    loss = mtc_loss_q15(prediction, target);
    for (uint32_t index = 0; index < MTC_OUTPUT_SIZE; ++index) {{
        int32_t difference = (int32_t)prediction[index] - target[index];
        mtc_delta_current[index] = mtc_saturate_q15((2 * difference) / (int32_t)MTC_OUTPUT_SIZE);
    }}
{chr(10).join(backward_blocks)}
    return loss;
}}
'''


def _render_train_source(config: ModelConfig) -> str:
    inputs = [_to_q15(value) for sample in config.training_data for value in sample.inputs]
    targets = [_to_q15(value) for sample in config.training_data for value in sample.targets]
    input_rows = []
    target_rows = []
    input_width = len(config.training_data[0].inputs)
    target_width = len(config.training_data[0].targets)
    for sample_index in range(len(config.training_data)):
        input_start = sample_index * input_width
        target_start = sample_index * target_width
        input_rows.append("    {" + ", ".join(map(str, inputs[input_start:input_start + input_width])) + "}")
        target_rows.append("    {" + ", ".join(map(str, targets[target_start:target_start + target_width])) + "}")
    return f'''/* Generated by MTC {__import__("mtc_compiler").__version__}. Do not edit. */
#include "mtc_model.h"

#include <inttypes.h>
#include <stdint.h>
#include <stdio.h>

static const int16_t mtc_training_inputs[MTC_TRAIN_SAMPLES][MTC_INPUT_SIZE] = {{
{",\n".join(input_rows)}
}};
static const int16_t mtc_training_targets[MTC_TRAIN_SAMPLES][MTC_OUTPUT_SIZE] = {{
{",\n".join(target_rows)}
}};

int main(void) {{
    mtc_reset();
    for (uint32_t epoch = 0; epoch < MTC_EPOCHS; ++epoch) {{
        int64_t total_loss = 0;
        for (uint32_t sample = 0; sample < MTC_TRAIN_SAMPLES; ++sample) {{
            total_loss += mtc_train_sample(mtc_training_inputs[sample],
                                           mtc_training_targets[sample]);
        }}
        printf("epoch=%" PRIu32 " loss_q15=%" PRId64 "\\n",
               epoch + 1U, total_loss / MTC_TRAIN_SAMPLES);
    }}
    return 0;
}}
'''


def _render_wokwi_sketch(config: ModelConfig) -> str:
    model_name = json.dumps(config.name)[1:-1]
    input_width = len(config.training_data[0].inputs)
    target_width = len(config.training_data[0].targets)
    input_rows = [
        "    {" + ", ".join(str(_to_q15(value)) for value in sample.inputs) + "}"
        for sample in config.training_data
    ]
    target_rows = [
        "    {" + ", ".join(str(_to_q15(value)) for value in sample.targets) + "}"
        for sample in config.training_data
    ]
    return f'''/* Generated by MTC {__version__}. Upload with mtc_model.c and mtc_model.h. */
#include <Arduino.h>
#include <stdint.h>
#include "mtc_model.h"

static const int16_t training_inputs[MTC_TRAIN_SAMPLES][MTC_INPUT_SIZE] = {{
{",\n".join(input_rows)}
}};
static const int16_t training_targets[MTC_TRAIN_SAMPLES][MTC_OUTPUT_SIZE] = {{
{",\n".join(target_rows)}
}};

static uint32_t epoch = 0;
static bool training_complete = false;

void setup() {{
    Serial.begin(115200);
    delay(250);
    mtc_reset();
    Serial.printf("MTC ESP32 trainer: {model_name}\\n");
    Serial.printf("Q15 | samples=%u | epochs=%u | static_ram=%u bytes\\n",
                  (unsigned)MTC_TRAIN_SAMPLES, (unsigned)MTC_EPOCHS,
                  (unsigned)MTC_STATIC_RAM_BYTES);
}}

void loop() {{
    if (training_complete) {{
        delay(1000);
        return;
    }}
    if (epoch >= MTC_EPOCHS) {{
        training_complete = true;
        int16_t prediction[MTC_OUTPUT_SIZE];
        for (uint32_t sample = 0; sample < MTC_TRAIN_SAMPLES; ++sample) {{
            mtc_forward(training_inputs[sample], prediction);
            Serial.printf("sample=%u target=%.4f output=%.4f\\n", (unsigned)sample,
                          (double)training_targets[sample][0] / 32768.0,
                          (double)prediction[0] / 32768.0);
        }}
        Serial.println("training complete");
        return;
    }}

    int64_t total_loss = 0;
    for (uint32_t sample = 0; sample < MTC_TRAIN_SAMPLES; ++sample) {{
        total_loss += mtc_train_sample(training_inputs[sample], training_targets[sample]);
    }}
    ++epoch;
    const float mean_loss = (float)total_loss / (float)MTC_TRAIN_SAMPLES / 32768.0f;
    Serial.printf("epoch=%lu loss=%.6f\\n", (unsigned long)epoch, mean_loss);
}}
'''


def _render_wokwi_diagram() -> str:
    return json.dumps(
        {
            "version": 1,
            "author": "Micro-Train-Compiler",
            "editor": "wokwi",
            "parts": [{
                "type": "wokwi-esp32-devkit-v1",
                "id": "esp",
                "top": 0,
                "left": 0,
                "attrs": {},
            }],
            "connections": [],
            "dependencies": {},
        },
        indent=2,
    ) + "\n"


def compile_model(
    config: ModelConfig,
    target: str = "esp32",
    allow_clipping: bool = False,
) -> Compilation:
    validate_model(config)
    if target not in TARGET_RAM_BUDGETS:
        raise ConfigError(f"Unsupported target {target!r}")
    if not config.training_data:
        raise ConfigError("compile requires non-empty 'training_data' in the model JSON")

    stages = build_stages(config)
    try:
        memory = plan_memory(config, stages, TARGET_RAM_BUDGETS[target])
    except ValueError as error:
        raise ConfigError(str(error)) from error
    analysis = analyze_ranges(config, stages)
    if analysis.overflows and not allow_clipping:
        overflow = analysis.overflows[0]
        raise ConfigError(
            f"Q15 overflow predicted at stage {overflow.stage} {overflow.operation}: "
            f"[{overflow.interval.min:.6g}, {overflow.interval.max:.6g}]; "
            "set --allow-clipping to emit saturating arithmetic"
        )

    weights, _ = _weight_values(stages, config.seed)
    weight_offsets, bias_offsets, _ = _weight_offsets(stages)
    files = {
            "mtc_model.h": _render_header(config, stages, memory),
            "mtc_model.c": _render_model_source(
                config, stages, memory, weights, weight_offsets, bias_offsets
            ),
        }
    if target == "wokwi":
        files.update({
            "sketch.ino": _render_wokwi_sketch(config),
            "diagram.json": _render_wokwi_diagram(),
        })
    else:
        files.update({
            "mtc_train.c": _render_train_source(config),
            "CMakeLists.txt": """cmake_minimum_required(VERSION 3.12)
project(mtc_generated C)
set(CMAKE_C_STANDARD 99)
set(CMAKE_C_STANDARD_REQUIRED ON)
add_executable(mtc_train mtc_model.c mtc_train.c)
target_compile_options(mtc_train PRIVATE -Wall -Wextra -Werror)
""",
        })
    return Compilation(
        files=files,
        stages=stages,
        analysis=analysis,
        memory=memory,
        target=target,
    )


def emit_project(
    config: ModelConfig,
    output: str | Path,
    target: str = "esp32",
    allow_clipping: bool = False,
) -> Compilation:
    compilation = compile_model(config, target=target, allow_clipping=allow_clipping)
    output_path = Path(output)
    output_path.mkdir(parents=True, exist_ok=True)
    for filename, contents in compilation.files.items():
        (output_path / filename).write_text(contents, encoding="utf-8")
    return compilation